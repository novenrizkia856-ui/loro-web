// Copies contract outputs from the loro-contracts Foundry project into the site.
//
//   node tools/sync-contracts.mjs [path/to/loro-contracts] [--local]
//
// Always:  out/*.json ABIs     -> assets/loro-abi.js
//          out-vectors/*.json  -> tests/auction-vectors.json (if present)
// --local: deployments/local.json -> config/loro.local.js (Anvil addresses)
//
// Development tool only. The deployed site never runs it.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const local = args.includes("--local");
const root = resolve(args.find((a) => !a.startsWith("--")) ?? resolve(site, "../loro-contracts"));

const abiOf = (name) =>
  JSON.parse(readFileSync(resolve(root, `out/${name}.sol/${name}.json`), "utf8")).abi;

// Minimal ERC20 surface the app needs. Standard, so not generated.
const ERC20_ABI = [
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "allowance", stateMutability: "view", inputs: [{ name: "o", type: "address" }, { name: "s", type: "address" }], outputs: [{ name: "", type: "uint256" }] },
  { type: "function", name: "approve", stateMutability: "nonpayable", inputs: [{ name: "s", type: "address" }, { name: "v", type: "uint256" }], outputs: [{ name: "", type: "bool" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ name: "", type: "string" }] },
  { type: "error", name: "ERC20InsufficientBalance", inputs: [{ name: "sender", type: "address" }, { name: "balance", type: "uint256" }, { name: "needed", type: "uint256" }] },
  { type: "error", name: "ERC20InsufficientAllowance", inputs: [{ name: "spender", type: "address" }, { name: "allowance", type: "uint256" }, { name: "needed", type: "uint256" }] }
];

const banner =
  "/* GENERATED by tools/sync-contracts.mjs from loro-contracts build output.\n" +
  "   Do not edit by hand. Rebuild the contracts and re-run the tool. */\n\n";

writeFileSync(
  resolve(site, "assets/loro-abi.js"),
  banner +
    `export const LORO_LOAN_ABI = ${JSON.stringify(abiOf("LoroLoan"), null, 2)};\n\n` +
    `export const LORO_LENS_ABI = ${JSON.stringify(abiOf("LoroLens"), null, 2)};\n\n` +
    `export const ERC20_ABI = ${JSON.stringify(ERC20_ABI, null, 2)};\n`
);
console.log("wrote assets/loro-abi.js");

const vectors = resolve(root, "out-vectors/auction-vectors.json");
if (existsSync(vectors)) {
  writeFileSync(resolve(site, "tests/auction-vectors.json"), readFileSync(vectors));
  console.log("wrote tests/auction-vectors.json");
}

if (local) {
  const d = JSON.parse(readFileSync(resolve(root, "deployments/local.json"), "utf8"));
  const body = {
    contracts: { loroLoan: d.loroLoan, loroLens: d.loroLens },
    stablecoin: { address: d.stablecoin, symbol: "mUSD", decimals: 6 },
    collateral: [
      { address: "0x0000000000000000000000000000000000000000", symbol: "ETH", name: "Ether", decimals: 18 },
      { address: d.stockA, symbol: "mSTKA", name: "Mock Stock Token A", decimals: 18 },
      { address: d.stockB, symbol: "mSTKB", name: "Mock Stock Token B", decimals: 18 }
    ]
  };
  writeFileSync(
    resolve(site, "config/loro.local.js"),
    "/* GENERATED for local Anvil development by tools/sync-contracts.mjs --local.\n" +
      "   Mock tokens only. Never deployed; excluded from Vercel by .vercelignore. */\n\n" +
      `export const localDeployment = ${JSON.stringify(body, null, 2)};\n`
  );
  console.log("wrote config/loro.local.js");
}
